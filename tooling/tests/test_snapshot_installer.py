def test_selective_upgrade_preserves_other_snapshot_links_and_custom_rule(source, tmp_path):
    root, old = source
    rules = tmp_path / "rules"
    rules.mkdir()
    rule = rules / "cometweb-agent-skills.mdc"
    rule.write_text("custom user rule")
    args = ("--rules-target", str(rules))
    assert run(root, old, tmp_path, *args, host="cursor").returncode == 0
    prior = os.readlink(tmp_path / "target/retired")
    new = upgrade(root)
    result = run(root, new, tmp_path, *args, "--skill", "kept", "--replace-conflicts", host="cursor")
    assert result.returncode == 0, result.stderr
    assert os.readlink(tmp_path / "target/retired") == prior
    assert not (tmp_path / "target/added").exists()
    assert rule.read_text() == "custom user rule"
