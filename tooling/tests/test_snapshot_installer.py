def test_non_posix_snapshot_install_fails_before_accessing_paths(monkeypatch):
    spec = importlib.util.spec_from_file_location("snapshot_installer", ROOT / "scripts/install-snapshot.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    with monkeypatch.context() as patch:
        patch.setattr(module.os, "name", "nt")
        with pytest.raises(ValueError, match="POSIX"):
            module.install(None)


def test_verify_rejects_special_mode_bits_even_when_filesystem_cannot_set_them(tmp_path, monkeypatch):
    spec = importlib.util.spec_from_file_location("snapshot_installer", ROOT / "scripts/install-snapshot.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    path = tmp_path / "tree/SKILL.md"
    path.parent.mkdir()
    path.write_bytes(b"reviewed bytes")
    expected = module.manifest({"SKILL.md": (path.read_bytes(), path.stat().st_mode & 0o777)})
    (tmp_path / "manifest.json").write_text(json.dumps(expected))
    module.verify(tmp_path, expected)
    original_stat = Path.stat

    def special_stat(self, *args, **kwargs):
        result = original_stat(self, *args, **kwargs)
        if self == path:
            values = list(result)
            values[0] |= 0o4000
            return os.stat_result(values)
        return result

    monkeypatch.setattr(Path, "stat", special_stat)
    with pytest.raises(ValueError, match="permissions"):
        module.verify(tmp_path, expected)


