@pytest.mark.parametrize("host", HOSTS)
def test_selected_snapshot_keeps_committed_bytes_after_dirty_source_and_source_removal(source, tmp_path, host):
    root, ref = source
    first = run(root, ref, tmp_path, "--skill", "kept", host=host)
    assert first.returncode == 0, first.stderr
    target = tmp_path / "target" / "kept" / "SKILL.md"
    (root / "skills/kept/SKILL.md").write_text("dirty working tree bytes")
    second = run(root, ref, tmp_path, "--skill", "kept", host=host)
    assert second.returncode == 0, second.stderr
    assert target.read_text() == "reviewed old bytes"
    assert sorted(path.name for path in target.parent.parent.iterdir()) == ["kept"]
    assert not (tmp_path / "never-written-home").exists()
    assert not (tmp_path / "unused-rules").exists()
    shutil.rmtree(root)
    assert target.read_text() == "reviewed old bytes"


def upgrade(root):
    (root / "skills/kept/SKILL.md").write_text("reviewed new bytes")
    shutil.rmtree(root / "skills/retired")
    path = root / "skills/added/SKILL.md"
    path.parent.mkdir()
    path.write_text("added")
    return commit(root)


def test_upgrade_and_rollback_remove_only_other_snapshot_packages(source, tmp_path):
    root, old = source
    assert run(root, old, tmp_path).returncode == 0
    foreign = tmp_path / "target" / "own"
    foreign.mkdir()
    (foreign / "notes").write_text("private user data")
    new = upgrade(root)
    result = run(root, new, tmp_path, "--replace-conflicts")
    assert result.returncode == 0, result.stderr
    assert {path.name for path in foreign.parent.iterdir()} == {"kept", "added", "own"}
    assert (foreign.parent / "kept/SKILL.md").read_text() == "reviewed new bytes"
    result = run(root, old, tmp_path, "--replace-conflicts")
    assert result.returncode == 0, result.stderr
    assert {path.name for path in foreign.parent.iterdir()} == {"kept", "retired", "own"}
    assert (foreign / "notes").read_text() == "private user data"
    assert (foreign.parent / "kept/SKILL.md").read_text() == "reviewed old bytes"
    receipts = [json.loads(path.read_text()) for path in (tmp_path / "store").glob("transaction-*/receipt.json")]
    assert len(receipts) == 3 and {item["ref"] for item in receipts} == {old, new}


@pytest.mark.parametrize("tamper", ["bytes", "permission", "special_permission", "addition", "manifest", "symlink",
    pytest.param("fifo", marks=pytest.mark.skipif(not hasattr(os, "mkfifo"), reason="POSIX FIFO support"))])
def test_cached_snapshot_tamper_fails_even_if_manifest_is_rewritten(source, tmp_path, tamper):
    root, ref = source
    assert run(root, ref, tmp_path, "--skill", "kept").returncode == 0
    snapshot = tmp_path / "store" / ref
    path = snapshot / "tree/skills/kept/SKILL.md"
    if tamper == "bytes":
        path.write_text("tampered")
    elif tamper == "permission":
        path.chmod(0o777)
    elif tamper == "special_permission":
        path.chmod((path.stat().st_mode & 0o777) | 0o4000)
        if not path.stat().st_mode & 0o4000:
            pytest.skip("filesystem does not retain the requested SUID bit")
    elif tamper == "addition":
        (path.parent / "unexpected").write_text("added")
    elif tamper == "manifest":
        data = json.loads((snapshot / "manifest.json").read_text())
        data["skills/kept/SKILL.md"]["sha256"] = "0" * 64
        (snapshot / "manifest.json").write_text(json.dumps(data))
    elif tamper == "fifo":
        os.mkfifo(path.parent / "unexpected.pipe")
    else:
        path.unlink()
        path.symlink_to(root / "skills/kept/SKILL.md")
    before = os.readlink(tmp_path / "target" / "kept")
    result = run(root, ref, tmp_path, "--skill", "kept")
    assert result.returncode != 0 and "snapshot" in result.stderr
    assert os.readlink(tmp_path / "target" / "kept") == before


def test_failed_host_apply_restores_all_previous_links_and_user_data(source, tmp_path):
    root, old = source
    assert run(root, old, tmp_path).returncode == 0
    upgrade(root)
    added = tmp_path / "target/added"
    added.mkdir()
    (added / "private").write_text("must survive")
    script = root / "scripts/install-codex.sh"
    script.write_text(script.read_text() + '\nif [[ " $* " != *" --dry-run "* ]]; then exit 33; fi\n')
    failing = commit(root)
    before = {path.name: os.readlink(path) for path in (tmp_path / "target").iterdir() if path.is_symlink()}
    result = run(root, failing, tmp_path, "--replace-conflicts")
    assert result.returncode != 0
    after = {path.name: os.readlink(path) for path in (tmp_path / "target").iterdir() if path.is_symlink()}
    assert after == before
    assert (tmp_path / "store" / failing).exists(), "failure must occur during apply, not preview"
    assert (added / "private").read_text() == "must survive"
    assert not (tmp_path / "store/.install-lock").exists()
    assert len(list((tmp_path / "store").glob("transaction-*/receipt.json"))) == 1


